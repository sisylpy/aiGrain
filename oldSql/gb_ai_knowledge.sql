-- 知识库主表
CREATE TABLE gb_ai_knowledge (
    -- 基础信息
    gb_ai_knowledge_id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
    gb_ai_knowledge_uuid VARCHAR(64) UNIQUE COMMENT 'UUID唯一标识',

    -- 分类信息
    gb_ai_knowledge_type INT DEFAULT 0 COMMENT '对话类型: 0=通用, 1=促销, 2=公众号',
    gb_ai_knowledge_category VARCHAR(50) COMMENT '知识大类: coupon/menu/decorate/staff...',

    -- 内容信息
    gb_ai_knowledge_title VARCHAR(255) NOT NULL COMMENT '知识标题',
    gb_ai_knowledge_summary VARCHAR(500) COMMENT '摘要（1-3句话）',
    gb_ai_knowledge_content TEXT NOT NULL COMMENT '详细内容（支持富文本/Markdown）',

    -- 来源
    gb_ai_knowledge_source_url VARCHAR(500) COMMENT '原文来源URL',

    -- 标签体系（多标签，用逗号分隔存储）
    gb_ai_knowledge_tags VARCHAR(500) COMMENT '标签列表: 母亲节,满减,节日营销,低成本',

    -- 专家信息
    gb_ai_knowledge_author VARCHAR(100) COMMENT '专家/作者名称',
    gb_ai_knowledge_origin VARCHAR(200) COMMENT '来源: 钱多多/刘一刀/王装修...',

    -- 效果数据
    gb_ai_knowledge_effect_rating INT DEFAULT 0 COMMENT '效果评分 1-5',
    gb_ai_knowledge_effect_cases INT DEFAULT 0 COMMENT '应用案例数',
    gb_ai_knowledge_effect_note VARCHAR(500) COMMENT '效果说明',

    -- 适用条件
    gb_ai_knowledge_suitable_restaurant VARCHAR(500) COMMENT '适用餐厅类型',
    gb_ai_knowledge_suitable_budget VARCHAR(100) COMMENT '适用预算范围',
    gb_ai_knowledge_suitable_season VARCHAR(100) COMMENT '适用季节',

    -- 统计
    gb_ai_knowledge_view_count INT DEFAULT 0 COMMENT '查看次数',
    gb_ai_knowledge_use_count INT DEFAULT 0 COMMENT '被推荐/使用次数',

    -- 状态
    gb_ai_knowledge_status INT DEFAULT 1 COMMENT '状态: 0=草稿, 1=启用, 2=下架',

    -- 时间
    gb_ai_knowledge_publish_time DATETIME COMMENT '发布时间',
    gb_ai_knowledge_create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    gb_ai_knowledge_update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    -- 索引
    INDEX idx_category (gb_ai_knowledge_category),
    INDEX idx_type (gb_ai_knowledge_type),
    INDEX idx_tags (gb_ai_knowledge_tags),
    INDEX idx_status (gb_ai_knowledge_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI知识库主表';

